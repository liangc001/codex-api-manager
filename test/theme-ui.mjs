import { _electron as electron } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'manager-theme-ui-'));
const env = { ...process.env, CODEX_HOME: path.join(temp, 'codex'), CODEX_MANAGER_TEST_DATA: path.join(temp, 'data'), PORTABLE_EXECUTABLE_DIR: temp };
delete env.ELECTRON_RUN_AS_NODE;
const executable = process.argv[2];
const app = await electron.launch({ ...(executable ? { executablePath: path.resolve(executable), args: [] } : { args: ['.'] }), env });
try {
  const page = await app.firstWindow(), errors = [];
  await page.emulateMedia({ reducedMotion: 'reduce' });
  page.on('pageerror', e => errors.push(e.message));
  await page.waitForFunction(() => document.querySelector('#count').textContent === '0');
  await page.locator('#close-guide').click();
  const appearance = () => page.locator('html').getAttribute('data-theme');
  assert.equal(await appearance(), 'light');
  await page.locator('#settings').click();
  await page.locator('#theme-select').selectOption('dark');
  assert.equal(await appearance(), 'dark');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.locator('#settings').click();
  await page.locator('#theme-select').selectOption('dark');
  await page.locator('#settings-form button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#settings-notice').textContent === '已保存');
  await page.waitForFunction(() => !document.querySelector('#settings-form').hasAttribute('aria-busy'));
  await page.locator('#cancel-settings').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#count').textContent === '0');
  assert.equal(await appearance(), 'dark');
  await fs.mkdir('test-output', { recursive: true });
  await page.screenshot({ path: 'test-output/theme-dark-empty.png' });
  for (const [name, url] of [['日常使用', 'https://provider.example/v1'], ['备用 API', 'https://provider.example/v1'], ['开发环境', 'https://sandbox.example/v1']]) {
    await page.evaluate(p => window.codexManager.request('save', p), { name, url, key: 'fake-test-key', model: 'gpt-6-sol', effort: 'high', adapter: 'none' });
  }
  await page.evaluate(() => load());
  assert.equal(await page.locator('.profile-details-button').count(), 3);
  assert.equal(await page.locator('.profile-details-button').first().innerText(), '详情');
  await page.locator('[aria-label="查看详情 日常使用"]').click();
  assert.equal(await page.locator('.detail-notes').getAttribute('open'), null);
  await page.locator('.detail-notes summary').click();
  assert.equal(await page.locator('.detail-note-body').isVisible(), true);
  assert.ok((await page.locator('#api-details-content').textContent()).includes('其他电脑直接访问服务商的请求不可见'));
  assert.ok((await page.locator('#api-details-content').textContent()).includes('未启用用量查询'));
  assert.equal(await page.locator('#details-refresh').isDisabled(), true);
  assert.ok(!(await page.locator('#api-details-content').textContent()).includes('fake-test-key'));
  await page.locator('#details-edit').click();
  assert.equal(await page.locator('#profile-form [name=name]').inputValue(), '日常使用');
  await page.locator('#cancel-editor').click();
  await page.evaluate(() => {
    const p = state.profiles.find(p => p.name === '日常使用');
    p.usage = { status: 'ok', scope: '此 Key 额度', remaining: 120, used: 30, today: 2, tokens: 1000, unit: 'USD', checkedAt: Date.now(), windows: [{ name: 'daily', used: 2, limit: 10 }] };
    openApiDetails(p.id);
  });
  const detailText = await page.locator('#api-details-content').textContent();
  for (const text of ['120 USD', '30 USD', '今日花费', '2 / 10 USD', '不能默认理解为今天或本月', '不是实时余额']) assert.ok(detailText.includes(text));
  await page.screenshot({ path: 'test-output/api-details-usage.png', fullPage: true });
  await page.locator('#close-api-details').click();
  await page.evaluate(() => load());
  for (const theme of ['light', 'dark']) {
    await page.locator('#settings').click();
    await page.locator('#theme-select').selectOption(theme);
    await page.waitForFunction(() => !document.querySelector('#settings-form').hasAttribute('aria-busy'));
    await page.screenshot({ path: `test-output/theme-${theme}-settings.png` });
    await page.locator('#settings-tab-general').focus();
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.locator('#settings-tab-data').getAttribute('aria-selected'), 'true');
    await page.locator('#retention-days').selectOption('7');
    await page.locator('#settings-tab-support').click();
    assert.equal(await page.locator('#export-diagnostics').isVisible(), true);
    await page.screenshot({ path: `test-output/theme-${theme}-settings-support.png` });
    await page.locator('#settings-tab-data').click();
    assert.equal(await page.locator('#retention-days').inputValue(), '7');
    await page.screenshot({ path: `test-output/theme-${theme}-settings-data.png` });
    await page.locator('#settings-form button[type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#settings-notice').textContent === '已保存');
    await page.waitForFunction(() => !document.querySelector('#settings-form').hasAttribute('aria-busy'));
    await page.locator('#cancel-settings').click();
    assert.equal((await page.evaluate(() => window.codexManager.request('state'))).settings.retentionDays, 7);
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.screenshot({ path: `test-output/theme-${theme}-${width}.png`, fullPage: true });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.locator('#settings').click();
      await page.locator('#settings-tab-data').click();
      await page.screenshot({ path: `test-output/settings-${theme}-${width}.png` });
      assert.ok(await page.locator('#save-settings').isVisible());
      assert.ok(await page.evaluate(() => document.querySelector('#settings-dialog').scrollWidth <= document.querySelector('#settings-dialog').clientWidth));
      await page.locator('#cancel-settings').click();
      await page.locator('[aria-label="查看详情 日常使用"]').click();
      await page.screenshot({ path: `test-output/api-details-${theme}-${width}.png` });
      assert.ok(await page.evaluate(() => document.querySelector('#api-details').scrollWidth <= document.querySelector('#api-details').clientWidth));
      await page.locator('#close-api-details').click();
    }
    await page.setViewportSize({ width: 1000, height: 900 });
    await page.locator('#add').click();
    await page.screenshot({ path: `test-output/theme-${theme}-editor.png` });
    await page.locator('#cancel-editor').click();
    await page.locator('#export-file').click();
    await page.screenshot({ path: `test-output/theme-${theme}-export.png` });
    await page.locator('#cancel-transfer').click();
  }
  await app.evaluate(({ app, dialog }) => {
    const service = process.mainModule.require(app.getAppPath() + '/desktop/restart-codex.cjs');
    service.probe = async () => ({ running: true });
    service.restart = async () => ({ restarted: true });
    dialog.showMessageBox = async () => ({ response: 1 });
  });
  await page.locator('.profile').first().locator('.switch-button').click();
  await page.waitForFunction(() => !document.body.classList.contains('busy'));
  const order = await page.evaluate(() => document.querySelector('.current').compareDocumentPosition(document.querySelector('.monitor-section')) & Node.DOCUMENT_POSITION_FOLLOWING && document.querySelector('.monitor-section').compareDocumentPosition(document.querySelector('.list-section')) & Node.DOCUMENT_POSITION_FOLLOWING);
  assert.ok(order, 'Monitor must appear between the current API and API list');
  assert.ok(await page.evaluate(() => parseFloat(getComputedStyle(document.querySelector('.eyebrow')).fontSize) >= 14));
  await page.locator('#monitor-toggle').check();
  await page.waitForFunction(() => !document.body.classList.contains('busy'));
  await page.screenshot({ path: 'test-output/theme-dark-monitor-reminder.png', fullPage: true });
  await page.locator('#restart-later').click();
  await page.locator('#notice').evaluate(el => el.hidden = true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-output/theme-dark-complete.png', fullPage: true });
  await page.locator('#help').click();
  await page.screenshot({ path: 'test-output/theme-dark-guide.png' });
  await page.locator('#close-guide').click();
  await page.locator('#monitor-toggle').uncheck();
  await page.waitForFunction(() => !document.body.classList.contains('busy'));
  await page.locator('#settings').click();
  await page.locator('#theme-select').selectOption('system');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await page.locator('#settings-form button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#settings-notice').textContent === '已保存');
  await page.locator('#cancel-settings').click();
  assert.equal((await page.evaluate(() => window.codexManager.request('state'))).settings.theme, 'system');
  assert.deepEqual(errors, []);
  await page.locator('#settings').click();
  assert.equal(await page.locator('#theme-select option[value=rainbow]').count(), 0);
  await page.locator('.theme-unlock summary').click();
  await page.locator('#theme-password').fill('wrong');
  await page.locator('#unlock-theme').click();
  await page.waitForFunction(() => document.querySelector('#theme-unlock-status').textContent === '口令不正确。');
  assert.equal(await page.locator('#theme-select option[value=rainbow]').count(), 0);
  if (process.env.MANAGER_THEME_TEST_PASSWORD) {
  await page.locator('#theme-password').fill(process.env.MANAGER_THEME_TEST_PASSWORD);
  await page.locator('#theme-password').press('Enter');
  await page.waitForFunction(() => document.documentElement.dataset.palette === 'rainbow');
  assert.equal(await page.locator('#theme-password').inputValue(), '');
  await page.locator('#save-settings').click();
  await page.waitForFunction(() => !document.querySelector('#settings-form').hasAttribute('aria-busy'));
  await page.locator('#cancel-settings').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#count').textContent === '3');
  assert.equal(await page.locator('html').getAttribute('data-palette'), 'rainbow');
  if (await page.locator('#restart-later').isVisible()) await page.locator('#restart-later').click();
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: `test-output/theme-rainbow-${width}.png`, fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.evaluate(() => {
      const p = state.profiles.find(p => p.name === '日常使用');
      p.usage = { status: 'ok', remaining: 120, used: 30, today: 2, tokens: 1000, unit: 'USD', checkedAt: Date.now() };
      openApiDetails(p.id);
    });
    await page.screenshot({ path: `test-output/rainbow-details-${width}.png` });
    assert.ok(await page.evaluate(() => document.querySelector('#api-details').scrollWidth <= document.querySelector('#api-details').clientWidth));
    await page.locator('#close-api-details').click();
    await page.locator('#settings').click();
    await page.screenshot({ path: `test-output/rainbow-settings-${width}.png` });
    assert.ok(await page.evaluate(() => document.querySelector('#settings-dialog').scrollWidth <= document.querySelector('#settings-dialog').clientWidth));
    await page.locator('#cancel-settings').click();
  }
  await page.locator('#settings').click();
  assert.equal(await page.locator('#theme-select').inputValue(), 'rainbow');
  await page.locator('#theme-select').selectOption('dark');
  await page.locator('#cancel-settings').click();
  assert.equal(await page.locator('html').getAttribute('data-palette'), 'rainbow');
  }
  assert.deepEqual(errors, []);
  console.log('Theme UI passed: preview, cancel/Escape, save/reload, system changes, responsive screens and dialogs');
} finally { await app.close(); await fs.rm(temp, { recursive: true, force: true }); }
